#!/usr/bin/env node
// Cross-platform developer entry point (ADR-0003). No dependencies: Node built-ins only.
//
//   pnpm dev [--core]        stack + backend (bootRun) + web (vite)
//   pnpm stack:up [--core]   start the Compose stack and bootstrap buckets
//   pnpm stack:down          stop the stack (keeps volumes)
//   pnpm stack:reset         stop the stack and delete its volumes
//   pnpm stack:env           (re)print the backend environment derived from .env
//
// `--core` skips ONLYOFFICE and ClamAV (heavy on small machines); the health page then reports them as DISABLED.
import { spawn, spawnSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const composeDir = join(root, 'deploy', 'compose')
const envFile = join(composeDir, '.env')
const isWindows = process.platform === 'win32'

const SECRET_KEYS = [
  'POSTGRES_SUPERUSER_PASSWORD',
  'MEMO_MIGRATOR_PASSWORD',
  'MEMO_APP_PASSWORD',
  'S3_ADMIN_ACCESS_KEY',
  'S3_ADMIN_SECRET_KEY',
  'S3_APP_ACCESS_KEY',
  'S3_APP_SECRET_KEY',
  'ONLYOFFICE_JWT_SECRET',
]

const CORE_SERVICES = ['postgres', 'seaweedfs', 'mailpit']
const FULL_SERVICES = [...CORE_SERVICES, 'onlyoffice', 'onlyoffice-gateway', 'clamav']

function log(msg) {
  console.log(`[dev] ${msg}`)
}

/** Generates deploy/compose/.env with random local credentials on first use; adds missing keys later. */
export function ensureEnv() {
  const existing = existsSync(envFile) ? parseEnv(readFileSync(envFile, 'utf8')) : {}
  const missing = SECRET_KEYS.filter((k) => !existing[k])
  if (missing.length > 0) {
    for (const k of missing) existing[k] = randomBytes(24).toString('base64url')
    const body = Object.entries(existing)
      .map(([k, v]) => `${k}=${v}`)
      .join('\n')
    writeFileSync(
      envFile,
      `# Generated by scripts/dev.mjs for LOCAL development only. Never commit this file.\n${body}\n`,
      { mode: 0o600 },
    )
    log(`wrote ${missing.length} generated credential(s) to deploy/compose/.env`)
  }
  return existing
}

export function parseEnv(text) {
  const out = {}
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line)
    if (m) out[m[1]] = m[2]
  }
  return out
}

/** Environment for the host-run backend, derived from the stack credentials. */
export function backendEnv(env, { core }) {
  const out = {
    SPRING_PROFILES_ACTIVE: 'dev',
    MEMO_DB_URL: 'jdbc:postgresql://localhost:5432/memo',
    MEMO_DB_APP_PASSWORD: env.MEMO_APP_PASSWORD,
    MEMO_DB_MIGRATOR_PASSWORD: env.MEMO_MIGRATOR_PASSWORD,
    MEMO_S3_ENDPOINT: 'http://localhost:8333',
    MEMO_S3_ACCESS_KEY: env.S3_APP_ACCESS_KEY,
    MEMO_S3_SECRET_KEY: env.S3_APP_SECRET_KEY,
    MEMO_SMTP_HOST: 'localhost',
    MEMO_SMTP_PORT: '1025',
  }
  if (!core) {
    out.MEMO_DOCSERVER_URL = 'http://localhost:8081'
    out.MEMO_CLAMAV_HOST = 'localhost'
    out.MEMO_CLAMAV_PORT = '3310'
  }
  return out
}

function compose(args, { allowFail = false } = {}) {
  const full = ['compose', '--env-file', envFile, '-f', join(composeDir, 'compose.yaml'), '--profile', 'full', ...args]
  const r = spawnSync('docker', full, { stdio: 'inherit', cwd: composeDir })
  if (r.status !== 0 && !allowFail) {
    throw new Error(`docker ${full.join(' ')} failed with exit code ${r.status}`)
  }
  return r.status
}

function stackUp({ core }) {
  ensureEnv()
  const services = core ? CORE_SERVICES : FULL_SERVICES
  log(`starting ${core ? 'core' : 'full'} stack: ${services.join(', ')}`)
  if (!core) log('first start of ONLYOFFICE and ClamAV can take several minutes (signature download, warm-up)')
  compose(['up', '-d', '--wait', '--wait-timeout', '900', ...services])
  compose(['run', '--rm', 'storage-init'])
  log('stack is healthy')
}

function prefixed(name, child) {
  for (const stream of [child.stdout, child.stderr]) {
    let buf = ''
    stream.setEncoding('utf8')
    stream.on('data', (chunk) => {
      buf += chunk
      const lines = buf.split(/\r?\n/)
      buf = lines.pop() ?? ''
      for (const l of lines) console.log(`[${name}] ${l}`)
    })
  }
}

function killTree(child) {
  if (!child.pid || child.exitCode !== null) return
  if (isWindows) spawnSync('taskkill', ['/pid', String(child.pid), '/T', '/F'], { stdio: 'ignore' })
  else child.kill('SIGTERM')
}

function runApps({ core }) {
  const env = ensureEnv()
  // Absolute path: cmd.exe may not search the current directory (NoDefaultCurrentDirectoryInExePath).
  const gradlew = join(root, isWindows ? 'gradlew.bat' : 'gradlew')
  const backend = spawn(isWindows ? `"${gradlew}"` : gradlew, [':backend:bootRun', '--console=plain'], {
    cwd: root,
    env: { ...process.env, ...backendEnv(env, { core }) },
    shell: isWindows,
  })
  const web = spawn('pnpm', ['--filter', 'web', 'dev'], { cwd: root, env: process.env, shell: isWindows })
  prefixed('backend', backend)
  prefixed('web', web)
  log('backend: http://localhost:8080/api/v1/health   web: http://localhost:5173   mail: http://localhost:8025')
  const stop = () => {
    log('stopping backend and web (the stack keeps running; use pnpm stack:down)')
    killTree(backend)
    killTree(web)
    process.exit(0)
  }
  process.on('SIGINT', stop)
  process.on('SIGTERM', stop)
  backend.on('exit', (code) => code && log(`backend exited with ${code}`))
  web.on('exit', (code) => code && log(`web exited with ${code}`))
}

function main() {
  const [command = 'dev', ...rest] = process.argv.slice(2)
  const core = rest.includes('--core')
  switch (command) {
    case 'dev':
      stackUp({ core })
      runApps({ core })
      break
    case 'up':
      stackUp({ core })
      break
    case 'down':
      compose(['down'])
      break
    case 'reset':
      compose(['down', '--volumes', '--remove-orphans'])
      break
    case 'env': {
      const env = backendEnv(ensureEnv(), { core })
      for (const [k, v] of Object.entries(env)) console.log(`${k}=${v}`)
      break
    }
    default:
      console.error(`unknown command: ${command}`)
      process.exit(2)
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main()
  } catch (e) {
    console.error(`[dev] ${e.message}`)
    process.exit(1)
  }
}
